        private static EnumModel? GetEnumModel(GeneratorAttributeSyntaxContext ctx)
        {
            if (ctx.TargetSymbol is not INamedTypeSymbol symbol)
                return null;

            bool isFlags = symbol.GetAttributes()
                .Any(a => a.AttributeClass?.ToDisplayString() == FlagsAttributeFqn);

            // Lê o separador de [GenerateDescriptions('|')] ou [GenerateDescriptions(Separator = 'x')]
            char separator = '|';
            var genAttr = ctx.Attributes.FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == GenerateDescriptionsAttributeFqn);
            if (genAttr is not null)
            {
                if (genAttr.ConstructorArguments.Length > 0 && genAttr.ConstructorArguments[0].Value is char consSep)
                {
                    separator = consSep;
                }
                else
                {
                    var sepArg = genAttr.NamedArguments.FirstOrDefault(kv => kv.Key == "Separator");
                    if (sepArg.Key == "Separator" && sepArg.Value.Value is char sepChar)
                        separator = sepChar;
                }
            }

            var membersBuilder = ImmutableArray.CreateBuilder<EnumMemberModel>();
            
            foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>().Where(f => f.IsStatic && f.HasConstantValue))
            {
                var descAttr = field.GetAttributes()
                    .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == DescriptionAttributeFqn);

                string description = field.Name;
                if (descAttr is { ConstructorArguments.Length: > 0 } && descAttr.ConstructorArguments[0].Value is string desc)
                    description = desc;

                membersBuilder.Add(new EnumMemberModel(field.Name, description));
            }

            string? ns = symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString();

            return new EnumModel(
                @namespace: ns,
                enumName: symbol.Name,
                isFlags: isFlags,
                separator: separator,
                members: membersBuilder.ToImmutable(),
                accessibility: symbol.DeclaredAccessibility
            );
        }

